#!/usr/bin/env python3
"""Writes spoilsport.sed to stdout. Every move is one sed s/// on a 9-cell board.

Board: cells 0..8, read across rows, top to bottom.
'.' empty, 'X' the human, 'O' spoilsport.
"""
import sys

LINES = [(0, 1, 2), (3, 4, 5), (6, 7, 8),
         (0, 3, 6), (1, 4, 7), (2, 5, 8),
         (0, 4, 8), (2, 4, 6)]
CORNERS = [0, 2, 6, 8]
SIDES = [1, 3, 5, 7]


def lit(c):
    return {'.': r'\.', 'X': 'X', 'O': 'O', None: '.'}[c]


def rule(cells, e):
    """cells: pos -> char that must match. Spoilsport plays O at empty cell e."""
    cells = dict(cells)
    cells[e] = '.'
    pre = ''.join(lit(cells.get(i)) for i in range(e))
    post = ''.join(lit(cells.get(i)) for i in range(e + 1, 9))
    return 's/^\\(%s\\)\\.\\(%s\\)$/\\1O\\2/' % (pre, post)


def two_in_line(who):
    """Play the empty third cell of any line where `who` holds the other two."""
    out = []
    for ln in LINES:
        for e in ln:
            out.append(rule({c: who for c in ln if c != e}, e))
    return out


def forks(who):
    """Play the empty cell e where `who` would get two open lines of two."""
    out = []
    for e in [4] + CORNERS + SIDES:
        through = [ln for ln in LINES if e in ln]
        for i in range(len(through)):
            for j in range(i + 1, len(through)):
                a = [c for c in through[i] if c != e]
                b = [c for c in through[j] if c != e]
                for x in (0, 1):
                    for y in (0, 1):
                        out.append(rule({a[x]: who, a[1 - x]: '.',
                                         b[y]: who, b[1 - y]: '.'}, e))
    return out


def three(who):
    return ['^' + ''.join(who if i in ln else '.' for i in range(9)) + '$'
            for ln in LINES]


def main():
    w = []
    p = w.append
    p('#!/bin/sed -f')
    p('# spoilsport: tic-tac-toe that will not lose. One board per line,')
    p('# 9 cells of . X O read across rows; prints the board after its move.')
    p('# Generated by gen.py. Every move below is a single s/// substitution.')
    p('')
    p('# reject anything that is not a board')
    p('/^[.XO]\\{9\\}$/!{')
    p('s/.*/? not a board/')
    p('b')
    p('}')
    p('h')
    p('# count marks: cancel one X against one O until nothing pairs up.')
    p('# Left over must be nothing (I opened) or one X (you opened).')
    p('s/\\.//g')
    p(':pair')
    p('s/X\\(.*\\)O/\\1/')
    p('t pair')
    p('s/O\\(.*\\)X/\\1/')
    p('t pair')
    p('/^X\\{0,1\\}$/!{')
    p('s/.*/? not my turn/')
    p('b')
    p('}')
    p('g')
    p('# games that are already over')
    for pat in three('X'):
        p('/%s/{\ns/.*/? you already won/\nb\n}' % pat)
    for pat in three('O'):
        p('/%s/{\ns/.*/? I already won/\nb\n}' % pat)
    p('/\\./!{')
    p('s/.*/? board full/')
    p('b')
    p('}')
    p('t clear')
    p(':clear')
    sections = [
        ('1. win', two_in_line('O')),
        ('2. block', two_in_line('X')),
        ('3. fork', forks('O')),
        ('4. you hold opposite corners round my centre: attack from a side',
         [rule({0: 'X', 4: 'O', 8: 'X', 2: '.', 3: '.', 5: '.', 6: '.', 7: '.'}, 1),
          rule({2: 'X', 4: 'O', 6: 'X', 0: '.', 3: '.', 5: '.', 8: '.', 7: '.'}, 1)]),
        ('5. take the cell where you would fork', forks('X')),
        ('6. centre', [rule({}, 4)]),
        ('7. corner opposite yours', [rule({8 - c: 'X'}, c) for c in CORNERS]),
        ('8. any corner', [rule({}, c) for c in CORNERS]),
        ('9. any side', [rule({}, c) for c in SIDES]),
    ]
    for title, rules in sections:
        p('# --- ' + title)
        for r in rules:
            p(r)
            p('t moved')
    p('s/.*/? no move/')
    p('b')
    p(':moved')
    for pat in three('O'):
        p('/%s/{\ns/$/ spoilsport wins/\nb\n}' % pat)
    p('/\\./!s/$/ draw/')
    sys.stdout.write('\n'.join(w) + '\n')


if __name__ == '__main__':
    main()
